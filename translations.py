def localize_lab(lab, topic, level, action_id=None):
    copy = LAB_HI[(topic, level)]
    result = dict(lab)
    for key in ("scenario", "task", "hint", "evidence", "root_cause", "vulnerable", "secure", "secure_fix"):
        if key in result:
            result[key] = copy[key]
    if "actions" in result:
        result["actions"] = [{**action, "label": copy["actions"][action["id"]]} for action in result["actions"]]
    if "feedback" in result:
        result["feedback"] = "सही बचाव चुना गया।" if result["passed"] else copy["feedback"][action_id]
    return result
